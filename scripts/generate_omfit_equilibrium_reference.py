"""
Generate the OMFIT reference for the equilibrium profiles_1d fields that OMAS does not map.

OMFIT is not available in the imas_composer environment or in CI, so the reference is written to
tests/equilibrium_profiles_1d_omfit_reference.yaml and committed. Each slice is loaded with
OMFITgeqdsk.from_mdsplus and translated with OMFITgeqdsk.to_omas, which traces the flux surfaces with
OMFIT fluxSurfaces.

The repository is public, so the reference only holds slices whose equilibria are already published: the DIII-D
sample equilibria of FUSE.jl (FUSE.jl/sample/g<shot>.<time>_fix_ods_*.json), which were made from EFIT02 at these
times. (The g159177.02700 sample is the 133221 equilibrium with flipped signs, so 159177 is not used.)

Run it in an environment with OMFIT's dependencies (e.g. omfit_311) and access to the DIII-D MDSplus server.
OMFIT is not an installable package, so its checkout and an OMAS checkout go on PYTHONPATH:

    PYTHONPATH=<OMFIT-source>/omfit:<omas checkout> mamba run -n omfit_311 \
        python scripts/generate_omfit_equilibrium_reference.py
"""

import argparse
import os
import tempfile
from pathlib import Path

import yaml
from omfit_classes.omfit_eqdsk import OMFITgeqdsk

EFIT_TREE = "EFIT02"
# (shot, GTIME [ms], FUSE.jl sample the slice was published as)
REFERENCE_SLICES = [
    (133221, 1150.0, "g133221.01151_fix_ods_np.json"),
    (150219, 3200.0, "g150219.03200_fix_ods_pp.json"),
    (153298, 4400.0, "g153298.04400_fix_ods_nn.json"),
]
ODS_FIELDS = [
    "elongation",
    "triangularity_upper",
    "triangularity_lower",
    "r_inboard",
    "r_outboard",
    "geometric_axis.r",
    "geometric_axis.z",
    "trapped_fraction",
    "gm5",
]
# Well below the tolerances of tests/test_equilibrium_profiles_1d_omfit.py
SIGNIFICANT_DIGITS = 6
DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "tests" / "equilibrium_profiles_1d_omfit_reference.yaml"
HEADER = """\
# OMFIT reference for the equilibrium profiles_1d fields that OMAS does not map, on the GEQDSK psi grid.
# Generated by scripts/generate_omfit_equilibrium_reference.py; do not edit by hand.
"""


def rounded(values) -> list[float]:
    return [float(f"{value:.{SIGNIFICANT_DIGITS}g}") for value in values]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT), help="Output YAML file")
    args = parser.parse_args()

    output = Path(args.output).resolve()
    # OMFITgeqdsk creates the g-file it is named after in the working directory, so keep those out of the repository
    os.chdir(tempfile.mkdtemp())

    slices = []
    for shot, time, fuse_sample in REFERENCE_SLICES:
        geqdsk = OMFITgeqdsk(f"g{shot}.{int(time):05d}").from_mdsplus(
            device="DIII-D", shot=shot, time=time, SNAPfile=EFIT_TREE, exact=True, quiet=True
        )
        profiles_1d = geqdsk.to_omas()["equilibrium.time_slice.0.profiles_1d"]
        profiles = {field: rounded(profiles_1d[field]) for field in ODS_FIELDS}
        # OMFIT's own b_field_average is the plain mean over the contour points; <|B|> is avg['Btot']
        profiles["b_field_average"] = rounded(geqdsk["fluxSurfaces"]["avg"]["Btot"])
        slices.append({"shot": shot, "time": time / 1000.0, "fuse_sample": fuse_sample, "profiles": profiles})
        print(f"{shot} at {time} ms")

    reference = {"efit_tree": EFIT_TREE, "slices": slices}
    output.write_text(HEADER + yaml.safe_dump(reference, sort_keys=False, default_flow_style=None, width=120))
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
